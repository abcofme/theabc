def tokens(n: int) -> str:
    """tokens(3) → '3 токена'"""
    mod10, mod100 = n % 10, n % 100
    if mod10 == 1 and mod100 != 11:
        word = "токен"
    elif 2 <= mod10 <= 4 and not 12 <= mod100 <= 14:
        word = "токена"
    else:
        word = "токенов"
    return f"{n} {word}"
