"""Build Caddy's RU matcher from a downloaded DB-IP Country Lite CSV archive."""
import argparse
import csv
import gzip
import hashlib
import ipaddress
import re
from pathlib import Path


def russian_networks(rows):
    networks = {4: [], 6: []}
    for number, row in enumerate(rows, 1):
        if len(row) != 3 or not re.fullmatch(r"[A-Z]{2}", row[2]):
            raise ValueError(f"Invalid country CSV row {number}")
        if row[2] != "RU":
            continue
        start, end = map(ipaddress.ip_address, row[:2])
        if start.version != end.version or int(start) > int(end):
            raise ValueError(f"Invalid address range on row {number}")
        networks[start.version].extend(ipaddress.summarize_address_range(start, end))
    return [network for version in (4, 6) for network in ipaddress.collapse_addresses(networks[version])]


def render_matcher(networks, release, digest):
    if not re.fullmatch(r"20[0-9]{2}-(0[1-9]|1[0-2])", release):
        raise ValueError("Release must be YYYY-MM")
    if not re.fullmatch(r"[a-f0-9]{64}", digest):
        raise ValueError("Invalid source SHA-256")
    return "\n".join([
        "# Generated by update_ru_ips.py; do not edit individual ranges.",
        f"# DB-IP IP to Country Lite, {release}; derived data: RU ranges only.",
        "# Source: https://db-ip.com/db/download/ip-to-country-lite",
        f"# Archive SHA-256: {digest}",
        "# IP Geolocation by DB-IP: https://db-ip.com/",
        "# License: Creative Commons Attribution 4.0 International",
        "# https://creativecommons.org/licenses/by/4.0/",
        *[f"remote_ip {network}" for network in networks],
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="dbip-country-lite-YYYY-MM.csv.gz")
    parser.add_argument("--release", required=True, help="YYYY-MM")
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("ru-ips.caddy"))
    args = parser.parse_args()
    digest = hashlib.sha256(args.archive.read_bytes()).hexdigest()
    with gzip.open(args.archive, "rt", encoding="utf-8-sig", newline="") as source:
        networks = russian_networks(csv.reader(source))
    # A partial or wrong download must not replace the deployed matcher.
    if len(networks) < 100 or {network.version for network in networks} != {4, 6}:
        raise ValueError("Expected a complete RU dataset covering both IPv4 and IPv6")
    result = render_matcher(networks, args.release, digest)
    temporary = args.output.with_suffix(".tmp")
    temporary.write_text(result, encoding="utf-8")
    temporary.replace(args.output)
    print(f"Generated {args.output.name}: {len(networks)} RU networks, release {args.release}")


if __name__ == "__main__":
    main()
